import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(readFileSync(join(root, "themes.json"), "utf8"));
const template = readFileSync(join(root, "gallery.template.html"), "utf8");
const checkOnly = process.argv.includes("--check");
const cssName = (name) => `--${name.replaceAll(".", "-")}`;
const luminance = (hex) => {
  const rgb = hex.slice(1).match(/../g).map((v) => parseInt(v, 16) / 255);
  const linear = rgb.map((v) => v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
  return linear[0] * 0.2126 + linear[1] * 0.7152 + linear[2] * 0.0722;
};
const contrast = (a, b) => {
  const values = [luminance(a), luminance(b)].sort((a, b) => b - a);
  return (values[0] + 0.05) / (values[1] + 0.05);
};
const checks = [];
const add = (fg, bg, minimum = 4.5) => checks.push([fg, bg, minimum]);
const surfaces = ["surface.canvas", "surface.panel", "surface.subtle", "surface.hover", "selection.background"];
for (const bg of surfaces) {
  for (const fg of ["text.primary", "text.secondary", "text.accent"]) add(fg, bg);
  add("border.control", bg, 3);
  add("focus.ring", bg, 3);
  for (let lane = 1; lane <= 4; lane++) add(`graph.lane.${lane}`, bg, 3);
}
for (const bg of ["action.primary", "action.primary.hover", "action.primary.active"]) add("action.onPrimary", bg);
add("selection.text", "selection.background");
for (const role of ["git.add", "git.delete", "status.success", "status.warning", "status.error", "status.info"]) {
  add(`${role}.text`, `${role}.background`);
  add("text.primary", `${role}.background`);
}

const expected = Object.keys(data.schemes[0].modes.light).sort().join(",");
const ids = new Set();
const results = [];
let failures = 0;
const rows = [];
for (const scheme of data.schemes) {
  if (!/^[a-z]+$/.test(scheme.id) || ids.has(scheme.id)) throw new Error("Invalid or duplicate scheme ID");
  ids.add(scheme.id);
  for (const mode of ["light", "dark"]) {
    const tokens = scheme.modes[mode];
    if (Object.keys(tokens).sort().join(",") !== expected) throw new Error(`Token mismatch: ${scheme.id}/${mode}`);
    for (const [key, value] of Object.entries(tokens)) {
      if (!/^#[0-9a-f]{6}$/i.test(value)) throw new Error(`Invalid sRGB hex: ${key}`);
    }
    let textMin = Infinity;
    let graphicMin = Infinity;
    for (const [fg, bg, target] of checks) {
      if (!tokens[fg] || !tokens[bg]) throw new Error(`Missing pair ${fg}/${bg}`);
      const ratio = contrast(tokens[fg], tokens[bg]);
      const pass = ratio >= target;
      if (!pass) failures++;
      if (target === 4.5) textMin = Math.min(textMin, ratio);
      else graphicMin = Math.min(graphicMin, ratio);
      results.push({ scheme: scheme.id, mode, foreground: fg, background: bg, ratio, target, pass });
    }
    rows.push(`| ${scheme.name} | ${mode} | ${textMin.toFixed(2)}:1 | ${graphicMin.toFixed(2)}:1 | ${checks.length} |`);
  }
}
const knownVars = new Set([...Object.keys(data.foundations), ...Object.keys(data.schemes[0].modes.light)].map(cssName));
for (const [, name] of template.matchAll(/var\((--[a-zA-Z0-9-]+)/g)) {
  if (!knownVars.has(name)) throw new Error(`Undefined template token: ${name}`);
}
if (failures) {
  console.error(results.filter((result) => !result.pass));
  throw new Error(`${failures} contrast checks failed`);
}

const definitions = Object.entries(data.foundations).map(([key, value]) => `${cssName(key)}: ${value};`).join("\n");
const html = template.replace("/* FOUNDATION_TOKENS */", definitions).replace("/* THEME_DATA */ null", JSON.stringify(data).replaceAll("<", "\\u003c"));
const report = `# Palette contrast evidence\n\nGenerated by \`bun docs/design-system/build.mjs\` from \`themes.json\`.\n\nThese are proposed opaque sRGB token pairs, not a product accessibility certification.\nRatios use WCAG relative luminance, with unrounded values compared against thresholds.\nNormal text requires 4.5:1; controls, focus rings, and graph lanes require 3:1\nagainst the declared adjacent surfaces. Decorative separators and disabled controls\nare excluded. No claim is made about contrast between graph lanes, color-vision\ndistinguishability, native dialogs, transparency, or operating-system rendering.\n\n| Scheme | Mode | Lowest text contrast | Lowest non-text contrast | Pairs checked |\n|---|---|---:|---:|---:|\n${rows.join("\n")}\n\nAll ${results.length} declared pairs pass. Full evidence: [contrast.csv](contrast.csv).\nThe gallery intentionally uses text labels, +/− diff markers, and graph topology\nas additional cues; rendered accessibility still needs verification during implementation.\n`;
const csv = "scheme,mode,foreground,background,ratio,target,pass\n" + results.map((r) => [r.scheme, r.mode, r.foreground, r.background, r.ratio.toFixed(6), r.target, r.pass].join(",")).join("\n") + "\n";
for (const [name, content] of [["gallery.html", html], ["CONTRAST.md", report], ["contrast.csv", csv]]) {
  if (checkOnly) {
    if (readFileSync(join(root, name), "utf8") !== content) throw new Error(`Regenerate ${name}`);
  } else writeFileSync(join(root, name), content);
}
console.log(`${data.schemes.length} schemes, 12 palettes, ${results.length} contrast pairs pass; generated files ${checkOnly ? "current" : "written"}.`);
